const assert = require('node:assert/strict')
const { readGuide, buildGuideContext } = require('../src/main/work-guides')
const { toolAllowedForAssignment } = require('../src/main/agent-quality')
const catalog = readGuide().guides
assert.equal(catalog.filter(g => g.scope === 'design').length, 21)
assert.equal(new Set(catalog.map(g => g.id)).size, catalog.length)
for (const entry of catalog) assert(readGuide(entry.id).instructions.length > 50)
assert.equal(readGuide('__proto__').success, false)
assert(readGuide('agent-cost').reference.path.endsWith('/cost-optimization.md'))
assert.equal(readGuide('agent-prompt-audit').reference.adapted, true)
assert(buildGuideContext('Аудит промпта', false, {fast:true}).includes('[agent-prompt-audit;'))
assert(buildGuideContext('Бенчмарк качества', false, {fast:true}).includes('[agent-eval;'))
assert(!buildGuideContext('Fast', false, {toolsAvailable:false}).includes('read_guide({'))
assert.equal(readGuide('export-as-pptx-editable').status, 'unavailable')
assert(buildGuideContext('3D монеты', true).includes('[3d-object; partial]'))
assert(!buildGuideContext('3D монеты', true).includes('[agent-review;'))
assert(buildGuideContext('Проверь и исправь ошибку').includes('[agent-verify;'))
assert(buildGuideContext('Привет').length < 250)
assert(toolAllowedForAssignment('read_guide', true))
assert(toolAllowedForAssignment('dc_check', true))
const full = catalog.map(g => readGuide(g.id).instructions).join('\n').length
const routed = buildGuideContext('Сделай интерактивный прототип сайта', true).length
assert(routed < full / 2)
console.log(JSON.stringify({ ok: true, guides: catalog.length, fullInstructionChars: full, routedInstructionChars: routed }))
