'use strict'
const assert = require('node:assert/strict')
const { createDeskModel } = require('../src/main/desk-model.cjs')

let serial = 0
const model = createDeskModel({ idFactory: () => `desk-${++serial}`, title: 'Рабочая среда' })
const rect = { x: 16, y: 16, width: 480, height: 320, z: 1 }
const add = title => ({ type: 'add', block: { kind: 'browser', title, resourceRef: 'resource:source', rect } })
const command = (id, revision, operations, actorId = 'human:window') => ({ operationId: id, expectedRevision: revision, operations, actorId })
const run = value => model.apply(value)

assert.equal(model.snapshot().revision, 0)
assert.equal(model.preview(command('preview', 0, [add('Черновик')])).ok, true)
assert.equal(model.snapshot().revision, 0)
assert.equal(model.snapshot().blocks.length, 0)
const first = run(command('create', 0, [add('Источник')]))
assert.equal(first.ok, true)
assert.equal(first.snapshot.revision, 1)
const id = first.snapshot.blocks[0].id
assert(id)
assert.equal(first.snapshot.blocks[0].revision, 1)
first.snapshot.blocks[0].title = 'Чужое изменение копии'
assert.equal(model.snapshot().blocks[0].title, 'Источник')

const conflict = run(command('stale', 0, [{ type: 'remove', id }], 'agent:run'))
assert.equal(conflict.code, 'conflict')
assert.equal(conflict.snapshot.revision, 1)
assert.equal(model.snapshot().blocks.length, 1)

const before = model.snapshot()
assert.equal(run(command('atomic', 1, [add('Второй'), { type: 'remove', id: 'missing' }])).code, 'invalid')
assert.deepEqual(model.snapshot(), before)
assert.equal(run(command('bad-size', 1, [{ type: 'geometry', id, rect: { ...rect, width: NaN } }])).code, 'invalid')
assert.equal(run(command('undersized', 1, [{ type: 'geometry', id, rect: { ...rect, width: 200 } }])).code, 'invalid')
assert.equal(run(command('bad-kind', 1, [{ type: 'add', block: { ...add('X').block, kind: 'execute-anything' } }])).code, 'invalid')
assert.equal(run(command('bad-ref', 1, [{ type: 'add', block: { ...add('X').block, resourceRef: '' } }])).code, 'invalid')
assert.equal(run(command('bad-key', 1, [{ type: 'add', block: { ...add('X').block, command: 'run' } }])).code, 'invalid')
assert.equal(run(command('huge', 1, Array.from({ length: 65 }, () => add('X')))).code, 'invalid')
assert.equal(run(command('bad-actor', 1, [add('X')], '')).code, 'invalid')
assert.equal(run(command('wrong-actor', 1, [add('X')], 'arbitrary')).code, 'invalid')

assert.equal(model.hold(id, 'human:window').ok, true)
assert.equal(model.hold(id, 'human:other').code, 'busy')
assert.equal(run(command('agent-busy', 1, [{ type: 'geometry', id, rect }], 'agent:run')).code, 'busy')
assert.equal(run(command('human-edit', 1, [{ type: 'geometry', id, rect: { ...rect, x: 32 } }])).ok, true)
assert.equal(model.snapshot().blocks[0].revision, 2)
model.releaseOwner('human:other')
assert.equal(run(command('still-busy', 2, [{ type: 'remove', id }], 'agent:run')).code, 'busy')
model.releaseOwner('human:window')
assert.equal(run(command('agent-edit', 2, [{ type: 'geometry', id, rect: { ...rect, x: 64 } }], 'agent:run')).ok, true)

const repeated = run(command('create', 0, [add('Источник')]))
assert.equal(repeated.ok, true)
assert.equal(repeated.replayed, true)
assert.equal(repeated.appliedRevision, 1)
assert.equal(repeated.snapshot.revision, 3)
assert.equal(model.snapshot().blocks.length, 1)
assert.equal(run(command('create', 0, [add('Другой')])).code, 'operation-reused')
assert.equal(run(command('create', 0, [add('Источник')], 'agent:other')).code, 'operation-reused')

assert.equal(model.hold('missing', 'human:window').code, 'invalid')
assert.equal(model.hold(id, 'agent:run').code, 'invalid')
assert.equal(run(command('remove', 3, [{ type: 'remove', id }])).ok, true)
assert.equal(model.snapshot().blocks.length, 0)

const capped = createDeskModel({ title: 'Limit' })
assert.equal(capped.apply(command('64', 0, Array.from({ length: 64 }, () => add('X')))).ok, true)
assert.equal(capped.apply(command('65', 1, [add('Overflow')])).code, 'invalid')
assert.equal(capped.snapshot().blocks.length, 64)
assert.throws(() => createDeskModel({ title: '' }))
const saved = model.snapshot()
const restored = createDeskModel({ initial: saved, title: 'Ignored' })
assert.deepEqual(restored.snapshot(), saved)
saved.title = 'Mutated copy'
assert.notEqual(restored.snapshot().title, saved.title)
assert.throws(() => createDeskModel({ initial: { ...saved, revision: -1 }, title: 'X' }))
assert.throws(() => createDeskModel({ initial: { ...saved, blocks: [{ id: 'bad' }] }, title: 'X' }))
let persisted
const durable = createDeskModel({ title: 'Saved', persist: next => { persisted = structuredClone(next) } })
assert.equal(durable.apply(command('persist', 0, [add('Keep')])).ok, true)
assert.deepEqual(persisted, durable.snapshot())
const broken = createDeskModel({ initial: persisted, persist: () => { throw Error('disk full') } })
assert.equal(broken.apply(command('failed', 1, [add('Lost')])).code, 'storage-unavailable')
assert.deepEqual(broken.snapshot(), persisted)
console.log('PASS desk model: revisions, atomic failure, validation, isolation, human holds, replay and limits')
