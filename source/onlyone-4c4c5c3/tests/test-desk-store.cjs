'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { createDeskStore } = require('../src/main/desk-store.cjs')
const { createDeskModel } = require('../src/main/desk-model.cjs')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'onlyone-desk-store-'))
// Test cipher only; production injects Electron safeStorage.
const protect = text => Buffer.from(text).toString('base64')
const unprotect = text => Buffer.from(text, 'base64').toString('utf8')
try {
  const store = createDeskStore({ dir, protect, unprotect })
  assert.equal(store.load('chat'), null)
  const model = createDeskModel({ title: 'Private title' })
  store.save('chat', model.snapshot())
  const target = path.join(dir, fs.readdirSync(dir)[0])
  const original = fs.readFileSync(target, 'utf8')
  assert(!original.includes('Private title'))
  assert.deepEqual(createDeskStore({ dir, protect, unprotect }).load('chat'), model.snapshot())
  const noKey = createDeskStore({ dir })
  assert.throws(() => noKey.load('chat'))
  assert.throws(() => noKey.save('chat', model.snapshot()))
  const broken = createDeskStore({ dir, protect: () => { throw Error('key unavailable') }, unprotect })
  assert.throws(() => broken.save('chat', model.snapshot()))
  assert.equal(fs.readFileSync(target, 'utf8'), original)
  assert.throws(() => store.save('../escape\n', model.snapshot()))
  fs.writeFileSync(target, JSON.stringify({ enc: 'safeStorage', data: protect(JSON.stringify({ chatId: 'other', snapshot: model.snapshot() })) }))
  assert.throws(() => store.load('chat'))
  fs.writeFileSync(target, '{broken')
  assert.throws(() => store.load('chat'))
  assert.equal(fs.readFileSync(target, 'utf8'), '{broken')
  fs.writeFileSync(target, 'x'.repeat(1024 * 1024 + 1))
  assert.throws(() => store.load('chat'))
  console.log('PASS Desk store: protected roundtrip, unavailable key, failure preservation, chat binding, corruption and size limits')
} finally { fs.rmSync(dir, { recursive: true, force: true }) }
