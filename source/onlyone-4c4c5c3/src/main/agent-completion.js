// Ход агента заканчивался ровно там, где модель переставала звать инструменты.
// Это не признак готовности, а признак того, что модель замолчала: она может
// замолчать после первого шага, объявив работу законченной, и приложение это
// примет. Владелец описал результат так — просил яблоко, получил апельсин, а в
// ответе написано «готово».
//
// Единственная существовавшая защита — saysUnfinished: регулярки по словам
// самого агента. Она срабатывает только когда агент честно признаёт недоделку,
// то есть в том случае, который и без неё не страшен. Ровно тот случай, на
// который жалуется владелец, она пропускает по построению.
//
// Здесь три проверки другого рода. Первые две ничего не стоят и опираются не на
// слова, а на факты хода: закрыт ли чек-лист и подтверждены ли утверждения
// ответа реальными вызовами. Третья — отдельный запрос, который сверяет
// исходную просьбу с тем, что реально сделано, и не видит ни рассуждений
// агента, ни его уверенного тона.

// Инструменты, которые действительно меняют что-то на диске или в дизайне.
// Всё остальное — чтение, и отчёт «я создал файл» им не подтверждается.
const { redactSecrets } = require('./run-checkpoints')

const MUTATION_TOOLS = new Set([
  'write_file', 'edit_file', 'create_directory', 'move_path', 'delete_path',
  'dc_write', 'dc_html_str_replace', 'dc_js_str_replace', 'dc_set_props',
  'dc_delete', 'dc_set_entry'
])

// Инструментов запуска в приложении нет вообще: ни оболочки, ни «выполнить
// команду». Единственный способ что-то запустить — написать себе инструмент
// через define_tool и позвать его как own_<имя>; MCP-сервер тоже может это
// уметь. Значит «прогнал тесты» без единого такого вызова — заведомо неправда,
// и это самый надёжный детектор вранья из возможных.
const RUNNER_PREFIXES = ['own_', 'mcp_']

const PLAN_STATUSES = ['todo', 'doing', 'done', 'blocked']

// ---------------------------------------------------------------------------
// Контракт завершения — то, что вставляется в системный промпт
// ---------------------------------------------------------------------------
// Написан как правила, а не как советы. Совет («старайся доводить до конца»)
// слабая модель округляет до нуля; правило с проверяемым условием — нет.
function completionContract({ defineTool = true } = {}) {
  const text = `

## Что значит «сделано»

Ход заканчивается, когда человек получил то, о чём просил, а не когда ты устал или закончил первый этап. Перечитай свой последний абзац перед финалом и сравни с типом запроса: если пользователь просил план, объяснение или аудит, такой ответ может быть полным результатом, а реализацию обещание не заменяет — продолжай доступные разрешённые действия. При отмене, отказе в разрешении, недоступном инструменте или внешнем блокере сообщи частичный результат и точное ограничение; запрет не обходи и новых полномочий не создавай.

**Сначала назови результат.** До первого инструмента одной строкой, в терминах задачи: «должен получиться установщик, который ставится поверх старой версии». Эта строка — мерка для всего хода, а не то, что оказалось удобно сделать.

**Чек-лист, когда шагов три и больше** (если подключён \`task_plan\`; простому ответу план не нужен). Пункт — проверяемый результат («Кнопка отмены прерывает запрос»), а не действие («Прочитать main.js»). Во время работы ровно один пункт в \`doing\`, не меньше и не больше; когда всё завершено или заблокировано, нет активного пункта и фиктивной работы заводить не нужно; закрывай пункт сразу, как он готов, а не пачкой в конце. Пункт **нельзя** помечать \`done\`, если реализация частичная, ошибка не разобрана, проверка не прошла или не запускалась, не нашёлся нужный файл или зависимость. При внешнем препятствии — \`blocked\` с причиной.

**Не отчитывайся о том, чего не делал.** «Создал», «исправил», «записал», «проверил», «запустил тесты» держатся на результате, который ты увидел на этом ходу: ответ инструмента, перечитанный файл, вывод команды с кодом завершения; имя инструмента запуск не доказывает. Запускают тем, что есть в списке (own_ или MCP-инструмент, в Design — dc_check). Не проверял — напиши «не проверял, потому что нет доступа к X»: одна такая строка полезнее уверенного тона. Проверка — доказательство, что работает, а не что существует: записал — перечитай, изменил поведение — найди, где оно проявляется. Сначала проверь изменённое место, шире — только при сбое.

**О неудаче говори в первом предложении ответа,** даже если остальное получилось. Частичный результат не называй завершённым: скажи, что сделано и чего не хватает.

## Ровно та задача, о которой просили

Объём — часть результата: его нельзя молча сузить, расширить или подменить, а согласованный объём нельзя уменьшать без согласия пользователя. Похожая задача, которую удобнее решить, не заменяет поставленную; поняв, что делаешь не то, остановись, скажи прямо и вернись к просьбе. При блокере можно сдать частичный результат, явно назвав незавершённое, — это не приёмка урезанной задачи. Если человек описывает проблему, спрашивает или размышляет вслух, результат — твоя оценка, а не правка кода: ответь и остановись.

## Менять решение — часть работы

Ты будешь ошибаться в выборе подхода; ненормально держаться за него, когда факты его опровергли. Если вернувшееся от инструмента противоречит плану, верь инструменту: скажи одной строкой, что не сработало и почему, и меняй подход; наблюдения под догадку не подгоняй. Неудавшийся подход не повторяй больше одного раза: второй такой же вызов после той же ошибки — зацикливание, меняй способ или называй блокер. Не обходи мешающую проверку — разберись, почему она не проходит. Признать неверную оценку — обычная работа, отдельным разделом об этом объявлять не нужно.

## Автономность и синтез инструментов

Только если \`define_tool\` есть в списке инструментов хода (в Design его нет — там dc_*). Для массовых операций и специфических проверок создай инструмент через \`define_tool\` и вызывай как \`own_<имя>\`. Если он вернул ошибку, используй сообщение, harnessHint и трассировку, исправь код повторным \`define_tool\` и запусти снова — доводи до работающего результата. После двух одинаковых ошибок смени подход; побочные действия вслепую не повторяй, отказ в разрешении не обходи, о нехватке прав или данных скажи конкретно.`
  // Без define_tool блок не к чему применять: он сам оговаривает это условием, но токены стоит и так.
  return defineTool ? text : text.slice(0, text.indexOf('\n\n## Автономность и синтез инструментов'))
}

// ---------------------------------------------------------------------------
// Чек-лист хода
// ---------------------------------------------------------------------------
// Форма намеренно совпадает с планом проекта: интерфейс уже умеет рисовать
// такой список с прогрессом, и второй способ рисовать то же самое был бы
// лишним кодом ради одинаковой картинки.
function normalizePlanItems(input, clean) {
  const cut = typeof clean === 'function' ? clean : (value, max) => String(value ?? '').trim().slice(0, max)
  const items = Array.isArray(input) ? input : []
  const seen = new Set()
  const out = []

  for (const item of items.slice(0, 40)) {
    const id = cut(item?.id, 60).replace(/[^A-Za-z0-9_-]/g, '')
    const title = cut(item?.title, 200)
    if (!id || !title || seen.has(id)) continue
    seen.add(id)
    out.push({
      id,
      title,
      detail: cut(item?.detail, 600),
      status: PLAN_STATUSES.includes(item?.status) ? item.status : 'todo',
      dependsOn: []
    })
  }
  return out
}

// Пункты, которые не закрыты. `blocked` считается незакрытым намеренно: агент,
// пометивший пункт блоком и замолчавший, обязан хотя бы назвать блокер вслух.
function openPlanItems(plan) {
  return (Array.isArray(plan) ? plan : []).filter(item => item && item.status !== 'done')
}

// ---------------------------------------------------------------------------
// Утверждения без доказательств
// ---------------------------------------------------------------------------
// Границу слова приходится писать вручную. `\b` в JavaScript определена через
// `\w`, то есть через латиницу: у кириллического слова границы в этом смысле
// нет вовсе, и `\bобновил\b` не совпадает ни с чем. Проверка молча пропускала
// бы всё, ради чего написана.
const EDGE_BEFORE = '(?<![\\p{L}\\p{N}_])'
const EDGE_AFTER = '(?![\\p{L}\\p{N}_])'

// Глагол изменения, дальше в том же предложении — что-то похожее на имя файла.
// Расширение обязано начинаться с буквы: иначе «версия 0.85.0» читается как
// файл «0.85.0», и проверка ловит сама себя.
const FILE_CLAIM = new RegExp(
  EDGE_BEFORE +
  '(созда(?:л|ла|н|но)|записа(?:л|ла|н|но)|обнови(?:л|ла)|исправи(?:л|ла)|поправи(?:л|ла)|добави(?:л|ла)|удали(?:л|ла)|переписа(?:л|ла)|переимен(?:овал|овала)|измени(?:л|ла)|created|wrote|updated|fixed|added|removed|deleted|renamed|modified)' +
  EDGE_AFTER +
  '[^.!?\\n]{0,90}?([-A-Za-z0-9_./\\\\]*[-A-Za-z0-9_]\\.[A-Za-z][A-Za-z0-9]{0,4})' + EDGE_AFTER,
  'giu')

// Только глаголы запуска. «Проверил» сюда не входит: проверить можно и чтением,
// и ложное срабатывание на честном ответе стоит дороже пропущенного вранья.
const RUN_CLAIM = new RegExp(
  EDGE_BEFORE + '(запусти(?:л|ла)|прогна(?:л|ла)|выполни(?:л|ла)|ran|executed)' + EDGE_AFTER +
  '[^.!?\\n]{0,70}?' + EDGE_BEFORE +
  '(тест|тесты|тестов|npm test|линтер|линт|сборк|команд|скрипт|test|tests|lint|build)',
  'giu')

function baseName(pathValue) {
  return String(pathValue || '').split(/[\\/]/).filter(Boolean).pop() || ''
}

function claimPath(value) {
  return String(value || '').replace(/\\/g, '/').replace(/^\.\//, '').toLowerCase()
}

function claimIsNegated(text, index) {
  const before = text.slice(Math.max(0, index - 60), index)
  return /(?:^|[\s(«"'])(?:не|нет|not|no|failed to|couldn't|could not|не удалось)\s+$/i.test(before)
}

// `log` — то же, что уходит в интерфейс строкой действия: { tool, detail, ok }.
// Возвращает список утверждений, под которыми в ходе нет ни одного вызова.
// Пусто — значит ответ сходится с делами; это обычный случай, и молчание здесь
// важнее, чем срабатывание.
function unsupportedClaims(answer, log) {
  const text = String(answer || '')
  if (!text.trim()) return []
  const calls = Array.isArray(log) ? log : []
  const claims = []

  const wrote = new Set()
  for (const call of calls) {
    if (call?.ok === false) continue
    if (!MUTATION_TOOLS.has(call?.tool)) continue
    const name = claimPath(call?.path || call?.detail)
    if (name) wrote.add(name)
  }

  // Многословный ответ повторяет одно и то же имя файла в разных падежах;
  // список претензий из десяти строк про один файл нечитаем.
  const named = new Set()
  FILE_CLAIM.lastIndex = 0
  let match
  while ((match = FILE_CLAIM.exec(text))) {
    // «Не записан», «не удалось обновить» — это признание, а не отчёт. Считать
    // его враньём значит наказывать ровно за ту честность, которой добиваемся.
    if (claimIsNegated(text, match.index)) continue
    const name = claimPath(match[2])
    if (!name || named.has(name)) continue
    named.add(name)
    const confirmed = wrote.has(name) || (!name.includes('/') && [...wrote].some(p => baseName(p) === name))
    if (!confirmed) {
      claims.push(`в ответе сказано «${match[1].toLowerCase()} ${match[2]}», но ни один успешный вызов этот файл не менял`)
    }
    if (claims.length >= 4) break
  }

  const ranSomething = calls.some(call =>
    call?.ok !== false && RUNNER_PREFIXES.some(prefix => String(call?.tool || '').startsWith(prefix)))
  RUN_CLAIM.lastIndex = 0
  const positiveRun = [...text.matchAll(RUN_CLAIM)].some(m => !claimIsNegated(text, m.index))
  if (!ranSomething && positiveRun) {
    claims.push('в ответе сказано о запуске тестов или команды, но в этом ходе не было ни одного вызова, который что-то запускает')
  }

  return claims
}

// ---------------------------------------------------------------------------
// Две бесплатные проверки одним решением
// ---------------------------------------------------------------------------
// Обе смотрят на факты хода, а не на формулировки, и обе ничего не стоят. Вынесены
// из цикла отдельной функцией не ради красоты: внутри семисотстрочного хода это
// был бы код, который нельзя запустить в тесте, а значит нельзя и проверить.
//
// Чек-лист идёт первым: свой собственный список, оставленный незакрытым, — самое
// прямое доказательство незавершённости, какое вообще бывает. Если он закрыт,
// проверяются требования задачи, а затем слова: отчёт «создал файл», под которым
// нет ни одного успешного вызова, — это и есть «наляпали и сказали, что сделали».
// Требования задачи живут отдельно от чек-листа модели: «сделано» в чек-листе
// лишь переводит требование в «проверяется». `task` — remainder() из
// task-state.cjs; null — требований нет и решают прежние проверки.
function taskGaps(task) {
  if (!task) return []
  const open = (Array.isArray(task.open) ? task.open : [])
    .map(item => `${item.expected} — не подтверждено доказательством`)
  const unknown = (Array.isArray(task.unknownActions) ? task.unknownActions : [])
    .map(item => `${item.tool}${item.target ? `: ${item.target}` : ''} — исход неизвестен, сначала проверь`)
  return [...open, ...unknown]
}

function completionGaps({ plan, answer, log, task = null } = {}) {
  const open = openPlanItems(plan)
  if (open.length) {
    return {
      lead: 'В чек-листе задачи остались незакрытые пункты:',
      gaps: open.map(item => `${item.title}${item.status === 'blocked' ? ' — помечен блоком' : ''}`)
    }
  }

  const pending = taskGaps(task)
  if (pending.length) {
    return { lead: 'Требования задачи не подтверждены доказательством:', gaps: pending }
  }

  const claims = String(answer || '').trim() ? unsupportedClaims(answer, log) : []
  if (claims.length) {
    return { lead: 'Ответ утверждает то, чего не подтверждает ни один вызов:', gaps: claims }
  }

  return { lead: '', gaps: [] }
}

