// Слой «превью и артефакты» (3.2). Прикладывается к тому режиму чата, в котором
// артефактные инструменты действительно подключены, — к разговору их не тянут:
// показывать панель там, где её показать нечем, хуже, чем не обещать вовсе.
const { cleanNames } = require('./tools')

const HOW = {
  show_artifact: '`show_artifact` — показать результат отдельной карточкой рядом с ответом',
  update_artifact: '`update_artifact` — править ту же работу, а не показывать вторую',
  show_video: '`show_video` — показать готовый ролик (файл из рабочей папки) в панели и блоке Ultra',
  artifacts_list: '`artifacts_list` — посмотреть, что в этом диалоге уже показано'
}

// Порядок перечисления: что показать, как править, как не задублировать.
const ORDER = ['show_artifact', 'update_artifact', 'show_video', 'artifacts_list']

// Видео (9.8): ролик — не текст ответа, а файл, который агент собрал сам.
function videoNote(names) {
  if (!names.includes('show_video')) return ''
  return `Видео. Ролик собирается файлом, а не пишется в ответ: ${names.includes('ffmpeg_info') ? '`ffmpeg_info` скажет, где ffmpeg, какой кодер здесь работает и с какими параметрами делать вертикальный ролик 1080×1920 (TikTok, Reels, Shorts); ' : ''}${names.includes('video_download') ? 'ссылку на референс скачивает `video_download`; ' : ''}${names.includes('video_analyze') ? '`video_analyze` разбирает файл по планам, ритму и звуку и отдаёт лист кадров; ' : ''}${names.includes('video_render_html') ? '`video_render_html` снимает твою HTML-страницу в ролик кадр за кадром по виртуальному времени (типографика, motion, графика; размер кадра — размер окна, 1080×1920 по умолчанию) — так делается всё, чего не собрать фильтрами; ' : ''}${names.includes('video_render') ? 'собирает ролик `video_render` — долгой задачей с долей в Центре задач, проверкой результата и показом в панели; ' : 'рендер идёт через run_command (долгий — с большим timeout_seconds), результат кладётся в рабочую папку, затем \`show_video\` с путём показывает его в панели и блоке Ultra. '}Так или иначе ролик в итоге виден в панели и блоке Ultra. Новая сборка того же ролика — снова show_video с id прежней. Референсы («сделай такое же») разбирай ffprobe и покадровыми пробами, называя, что именно взято: ритм монтажа, длительности планов, темп, подача текста, а не «похоже». Свой готовый ролик сверяй с референсом тем же video_analyze (число планов, длины, ритм) и правь расхождения. Если нужна серия роликов, делай один шаблон (страницу или команду) с параметрами и собирай серию подстановкой${names.includes('define_tool') ? ', а повторяемый процесс закрепляй своим инструментом (define_tool), чтобы в следующий раз не собирать заново' : ''}.

`
}

function build(ctx = {}) {
  const names = cleanNames(ctx.toolNames).filter(name => ORDER.includes(name))
  if (!names.length) return ''

  return `## Превью и артефакты

Результат, который человек будет разглядывать, а не читать, живёт не в тексте
ответа, а рядом с ним: панель показывает страницу живым превью, картинку,
таблицу, график, код или дифф. HTML, размеченный прямо в ответе, превью не
получит — человек увидит код.

${names.map(name => `- ${HOW[name]}`).join('\n')}

Для вида chart передавай JSON такого вида: {"type":"bar"|"line","title":"...","xLabel":"...","yLabel":"...","unit":"...","categories":["..."],"series":[{"name":"...","values":[1,2]}]}. Чисел в каждом values должно быть ровно столько же, сколько категорий. Поддерживаются столбчатая и линейная диаграммы; для одной и той же работы используй один вид и порядок категорий. Старый формат labels + datasets тоже читается, если в datasets есть label и числовой data.

Одна работа — один артефакт со своей историей версий. Правку того, что уже
показано, вноси новой версией той же записи: прежняя остаётся доступной, а
человек видит, что менялось. Второй артефакт на ту же работу он прочитает как
твою растерянность.

Артефакт — не файл проекта: он принадлежит диалогу и в рабочую папку не пишется.
Нужен файл в папке — пиши файл и скажи путь; нужен результат в чате — покажи
артефактом. И то и другое по просьбе, а не «на всякий случай».

Живое превью страницы открывается само, когда содержимое пригодно для просмотра.
Не утверждай, что видел, как оно выглядит: панель видит человек. Про свой результат
говори по содержимому, а не по впечатлению от рендера.

${videoNote(cleanNames(ctx.toolNames))}Макеты интерфейсов делаются в разделе «Дизайн» своими инструментами, и здесь их
нет: страница чата — это ответ, а не проектируемый продукт.`
}

module.exports = { id: 'artifacts', title: 'Превью и артефакты', build, appliesTo: 'artifacts' }
