// Кто выносит приёмку.
//
// Судья сверяет просьбу с тем, что сделано. Когда это та же модель, что работала, она склонна соглашаться со своей
// работой: свои рассуждения и свой тон она читает как доказательство. Другая модель того же класса этой склонности
// лишена. Судье не нужны инструменты и не нужна сила — нужно прочитать просьбу, список вызовов и ответ, — поэтому
// подходит любая бесплатная чат-модель из списка проверяющих, кроме той, что работала.
//
// Своя модель остаётся запасным вариантом: если подходящей другой нет, или она промолчала, спрашивается та, что работала.

function pickJudgeModel ({ lead, candidates = [], usable = () => true } = {}) {
  for (const id of candidates) {
    if (id && id !== lead && usable(id)) return id
  }
  return lead
}

module.exports = { pickJudgeModel }
