function starterList() {
  return Object.entries(STARTERS).map(([id, s]) => ({ id, title: s.title, what: s.what }))
}

function starter(kind) {
  const found = STARTERS[String(kind || '').trim()]
  if (!found) {
    return { success: false, error: 'Нет такой заготовки. Есть: ' + Object.keys(STARTERS).join(', ') }
  }
  return {
    success: true,
    title: found.title,
    b_dc_html: found.html,
    c_dc_js: found.js,
    check: found.check,
    note: 'Это каркас с готовой механикой, а не готовая работа. Замени содержимое, выбери свою типографику и палитру, поменяй композицию под задачу. Оставить как есть — значит сдать чужой макет.'
  }
}

function referenceList() {
  return Object.entries(REFERENCES).map(([id, r]) => ({ id, title: r.title }))
}

function reference(kind) {
  const found = REFERENCES[String(kind || '').trim()]
  if (!found) {
    return { success: false, error: 'Нет такого разбора. Есть: ' + Object.keys(REFERENCES).join(', ') }
  }
  return { success: true, title: found.title, structure: found.structure, variants: found.variants, watch: found.watch }
}

module.exports = { starterList, starter, referenceList, reference, STARTERS, REFERENCES }
