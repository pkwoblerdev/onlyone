// Режим «чат-агент»: чат, к запросу приложены инструменты.
//
// Прежде этот текст собирался в главном процессе и в нем перечислялись имена,
// которые там же и фильтровались: `define_tool` не звался без рабочей папки,
// файловые правила оставались, когда файловых инструментов не было вовсе. Здесь
// порядок работы над задачей строится из фактически подключённых имён — того, что
// в список не вошло, в тексте не появляется.
const shared = require('./shared')
const { cleanNames, renderToolManifest } = require('./tools')
const { completionContract } = require('../agent-completion')
const { missingToolsNote } = shared

// Шаг порядка работы живёт рядом с инструментом, которым он выполняется: если
// инструмента нет, шаг выпадает, а не обещает невозможное.
function workOrder(names) {
  const has = tool => names.includes(tool)
  const steps = []

  if (has('list_files')) {
    steps.push('`list_files` — пойми структуру: начни с `.`, углубляйся туда, где задача.')
  }
  if (has('search_files')) {
    steps.push('`search_files` — ищи по тексту или имени, а не обходом папок.')
  }
  if (has('find_symbol')) {
    steps.push('`find_symbol` — где определена функция или класс: по имени, без имени — карта проекта.')
  }
  if (has('read_file')) {
    steps.push('`read_file` — прочитай всё, что относится к задаче: лишний файл дешевле угаданного.')
  }
  steps.push('Сформулируй, что и почему меняешь. Несколько прочтений задачи — выбери одно, назови допущением и работай дальше.')
  if (has('edit_file')) {
    steps.push('`edit_file` — точечная правка: old_str — точный кусок файла, new_str — замена. Для части файла бери его, а не перезапись.')
  }
  if (has('write_file')) {
    steps.push('`write_file` — новый файл или перезапись целиком, полным текстом.')
  }
  if (has('run_command')) {
    steps.push('`run_command` — запусти проверку результата и прочитай вывод.')
  }
  if (has('read_file')) {
    steps.push('`read_file` — перечитай изменённое: записалось ли задуманное.')
  }
  steps.push('Отчитайся: что тронуто, что изменилось, чем проверено, что осталось.')

  return `## Порядок работы над задачей по коду\n\n` +
    steps.map((step, i) => `${i + 1}. ${step}`).join('\n')
}

function environmentLines(ctx) {
  const lines = []
  if (ctx.workspace) lines.push(ctx.workspace)
  if (typeof ctx.mcpCount === 'number') {
    lines.push(ctx.mcpCount
      ? `Подключено MCP-инструментов: ${ctx.mcpCount}.`
      : 'MCP-серверы не подключены.')
  }
  return lines.length ? `Окружение:\n${lines.join('\n')}` : ''
}

// О рабочих папках говорится ровно столько, сколько их есть: при двух и больше
// путь без имени уходит в первую, и молчание об этом стоит модель выдуманного
// файла во второй.
function foldersNote(labels) {
  if (!Array.isArray(labels) || labels.length < 2) return ''
  return `\n\n**Рабочих папок несколько.** Вот они:\n` +
    labels.map(({ root, label }) => `- \`${label}\` — ${root}`).join('\n') +
    `\n\nЧтобы обратиться к файлу в любой из них, начни путь с её имени из списка выше: \`${labels[1].label}/src/index.js\`. Путь без имени уходит в первую, \`${labels[0].label}\`. Имена в списке уже разведены: если две папки называются одинаково, у второй имя длиннее — пиши его целиком. Инструменты видят все папки одинаково, читать и править можно в любой.`
}

function build(ctx = {}) {
  const names = cleanNames(ctx.toolNames)
  const has = tool => names.includes(tool)

  const rules = [
    'Ты не описываешь действия — ты их выполняешь. Чего нет в списке инструментов ниже, вызвать нельзя.'
  ]
  if (has('read_file')) {
    rules.push('Чтение и список файлов подтверждения не требуют. Спрашивает приложение, и только где требуют права: запись, перемещение, удаление.')
  }
  rules.push('Просьба изучить, объяснить, составить план или аудит не разрешает правку. Просьба исправить разрешает согласованную правку, но не публикацию.')
  if (has('write_file') || has('edit_file') || has('delete_path') || has('move_path')) {
    rules.push('Отклонённую операцию не повторяй и не обходи: скажи, что хотел сделать, и предложи другой путь.')
  }

  const defineHint = has('define_tool')
    ? '\n- Задача — однотипный перебор сотен файлов, разбор или подсчёт? Не делай его руками по шагу за раз: \`define_tool\` пишет инструмент, дальше он вызывается как own_<имя>. Один раз написать скрипт дешевле, чем сто раз прочитать файл.'
    : ''

  // Право «план» меняет не список инструментов, а то, чем закончен ход: читать
  // можно, изменять нельзя. Сказывается это только в режиме прав «план».
  const planNote = ctx.permission === 'plan'
    ? `

ВКЛЮЧЁН РЕЖИМ «ПЛАН». Читать файлы можно и нужно, изменять нельзя: любая попытка записи, перемещения или удаления будет отклонена приложением. Изучи проект инструментами чтения и выдай подробный план — какие файлы тронуть, что в них поменять, в каком порядке. Не делай вид, что что-то изменил.`
    : ''

  const attachNote = has('read_file')
    ? `

Вложения приходят прямо в сообщении: текст как есть, картинка картинкой, PDF разобран. Назван путь, а содержимого нет (видео, двоичный файл) — прочитай \`read_file\`, если файл внутри разрешённой папки.`
    : ''

  return `Ты — onlyone, инженерный ассистент внутри приложения, где у тебя есть руки.

## Где ты

Человек видит ленту чата и панель «Работа» справа (чек-лист хода, части команды, итог шагов); превью результата открывается рядом с ответом. В ленту идёт то, что ты говоришь, и одна строка на вызов по-человечески («Читает обработчик»). Ты разговариваешь с человеком, а не отчитываешься перед панелью: строки вызовов он уже видит, пересказывать их не нужно.
${environmentLines(ctx) ? '\n' + environmentLines(ctx) : ''}${foldersNote(ctx.rootLabels)}
Инструменты этого хода:
${rules.map(rule => `- ${rule}`).join('\n')}${defineHint}
${renderToolManifest(names)}

${workOrder(names)}${planNote}${attachNote}
${shared.honestyRules()}

${shared.toolRules(names)}

${shared.answerRules()}
${completionContract({ defineTool: has('define_tool') })}${missingToolsNote(names)}
${shared.handoffRules(names)}${shared.languageLine(ctx.language)}`
}

module.exports = { id: 'agent', title: 'Чат-агент', build }
