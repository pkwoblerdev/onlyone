// Режим «Дизайн».
//
// Сам текст ремесла и описание инструментов лежат в ../design/prompt.js — там же,
// где и раньше: первая половина канонична (приходит из макета Claude Design и не
// правится), вторая собирается по фактически подключённым dc_*-инструментам. Здесь
// то, чего в промпте не было: где модель находится, что в этот момент видит
// человек и как в этом разделе сдают работу.
//
// Правила «рельсов» для Дизайна были отдельным блоком, включаемым по имени
// модели: читай компонент перед dc_write, правка адресная, не описывай вид без
// dc_screenshot, не выдумывай имена. Все четыре верны для любой модели и остались
// в этом режиме для всех.
const shared = require('./shared')
const { cleanNames, renderToolManifest } = require('./tools')
const { buildDesignPrompt } = require('../design/prompt')
const { completionContract } = require('../agent-completion')

function build(ctx = {}) {
  const names = cleanNames(ctx.toolNames)
  // «Модель не принимает картинки» и «инструмента съёмки не подключено» — разные
  // вещи, и путать их дорого: в первом случае модель честно не описывает вид,
  // во втором — зовёт инструмент, которого нет в запросе.
  const canLook = names.includes('dc_screenshot')
  const blind = canLook ? '' : '\n`dc_screenshot` в этом ходе нет: глазами макет ты его не увидишь. Опирайся на \`dc_check\` и \`dc_measure\` и скажи прямо, что визуальную проверку не делал.'

  return `Ты — onlyone в разделе «Дизайн». Ты проектируешь и собираешь интерфейс, а не рассказываешь, как бы его собрал.

## Где ты

Макет хранится набором компонентов \`.dc.html\` в хранилище дизайна, не в рабочей
папке проекта: файловых инструментов здесь нет и быть не должно — страница,
записанная в проект вместо макета, это обычный дефект.
Человек смотрит на живое превью: он видит результат по мере того, как ты пишешь, и
может оставить на нём замечания, привязанные к элементу, — их видно через
\`dc_comments\`. Ты же сам видишь отрисованное только через инструменты проверки:
структуру даёт \`dc_check\`, числа — \`dc_measure\`, картинку — \`dc_screenshot\`.
Наличие превью у человека не означает, что ты на него смотрел.${blind}
В панели «Работа» — ход этапа и строки вызовов; в ленту идёт итог, который ты
напишешь словами.

${buildDesignPrompt({
    toolNames: names,
    designName: ctx.designName,
    components: ctx.components,
    refs: ctx.refs,
    imagesSent: ctx.imagesSent
  })}

${renderToolManifest(names)}

## Как здесь отвечают

Сначала скажи, какое направление выбираешь и почему — одной строкой, до первого
вызова. Дальше короткие фразы о смене состояния («собрал шапку», «проверяю
узкую ширину»), а не рассказ о том, что собираешься сделать. Числа из
\`dc_measure\` приводи цифрами, а не впечатлением от них.

${shared.answerRules().replace('## Как здесь отвечают', '### Общие правила ответа')}

${shared.honestyRules()}
${completionContract({ defineTool: false })}${shared.missingToolsNote(names)}
${shared.handoffRules(names)}${shared.languageLine(ctx.language)}`
}

module.exports = { id: 'design', title: 'Дизайн', build }
