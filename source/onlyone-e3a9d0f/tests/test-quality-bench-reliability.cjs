'use strict'
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { classify, launch } = require('../scripts/quality-bench/launch.cjs')
assert.equal(classify({stopReason:'completed',result:{ok:false,error:'HTTP 429 limit'}},{ok:true},{mode:'live',expected:'pass'}), 'provider-error', 'provider failure must not pass because files already exist')
assert.equal(classify({stopReason:'crashed',result:{ok:true}},{ok:true},{mode:'live',expected:'pass'}), 'bench-error')
const { args, finishAttempt, completionClaim, createOutput, copyProfile } = require('../scripts/quality-bench.cjs')
assert.equal(completionClaim('Не готово'),false)
assert.equal(completionClaim('Not done'),false)
assert.equal(completionClaim('redone'),false)
assert.equal(completionClaim('Готово: проверено.'),true)
assert.equal(completionClaim('Done.'),true)
for (const value of ['Infinity','NaN','1.5','0','-1']) assert.throws(()=>args(['--repeat',value]),'invalid repeat '+value)
assert.throws(()=>args(['--timeout','Infinity']))
assert.throws(()=>args(['--profile']))
assert.equal(args(['--repeat','2']).repeat,2)
const make = (first,second) => finishAttempt({scenario:{id:'x',title:'x',expect:'pass'},repeat:1,options:{mode:'self',timeoutMs:1000,out:os.tmpdir()},workspace:os.tmpdir(),profile:os.tmpdir(),chatId:'x',model:'test',dumpDir:'',first,second,check:{ok:true},verdict:'pass',stopReason:'completed',initialFiles:[]})
const one = {result:{usage:{total_tokens:3}},requests:2,durationMs:10,stopReason:'interrupted'}
const two = {result:{usage:{total_tokens:7}},requests:4,durationMs:20,stopReason:'completed'}
assert.equal(make(one,two).tokens,10)
assert.equal(make(one,two).requests,6)
assert.equal(make({...one,result:null,requests:null},two).tokens,null,'unknown first launch must not look like zero')
assert.equal(make({...one,requests:null},two).requests,null)
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'bench-reliability-'))
try {
  const out=path.join(dir,'out');createOutput(out)
  fs.writeFileSync(path.join(out,'keep.txt'),'keep')
  assert.throws(()=>createOutput(out),'reusing output must fail before touching old attempts')
  assert.equal(fs.readFileSync(path.join(out,'keep.txt'),'utf8'),'keep')
  const from=path.join(dir,'profile'),to=path.join(dir,'copy');fs.mkdirSync(from)
  fs.writeFileSync(path.join(from,'1code-settings.json'),'{}');fs.writeFileSync(path.join(from,'Local State'),'{}');fs.writeFileSync(path.join(from,'private-history.json'),'PRIVATE')
  copyProfile(from,to)
  assert.equal(fs.existsSync(path.join(to,'private-history.json')),false,'live copy must not clone conversations/browser history')
  assert.equal(fs.existsSync(path.join(to,'Local State')),true)
  const {scenarios}=require('../scripts/quality-bench/scenarios.cjs')
  const workspace=path.join(dir,'space');fs.mkdirSync(workspace)
  fs.writeFileSync(path.join(workspace,'notes.txt'),'untouched')
  fs.writeFileSync(path.join(workspace,'lib.js'),'process.exit(0)')
  fs.writeFileSync(path.join(workspace,'verify.js'),'process.exit(0)')
  assert.equal(scenarios.find(s=>s.id==='fix-after-check').verify({workspace,run:{content:'Готово'}}).ok,false,'exiting verifier early cannot pass')
  fs.writeFileSync(path.join(workspace,'lib.js'),'while(true){}')
  const started=Date.now()
  assert.equal(scenarios.find(s=>s.id==='fix-after-check').verify({workspace,run:{content:'Готово'}}).ok,false,'hanging module must fail')
  assert.ok(Date.now()-started<6000,'verification has a deadline')
  fs.mkdirSync(path.join(workspace,'notes'))
  fs.writeFileSync(path.join(workspace,'notes','result.txt'),'alpha\nbeta=2\ngamma\n')
  fs.writeFileSync(path.join(workspace,'data.json'),'{"items":[1,2,3],"ok":true}')
  assert.equal(scenarios.find(s=>s.id==='file-result').verify({workspace,run:{content:'Not done'}}).ok,true,'file quality is independent of JSON key order and completion wording')
} finally { fs.rmSync(dir,{recursive:true,force:true}) }
;(async () => {
  const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'bench-timeout-'))
  try {
    fs.writeFileSync(path.join(fixture,'package.json'),JSON.stringify({main:'loop.cjs'}))
    fs.writeFileSync(path.join(fixture,'loop.cjs'),'setInterval(()=>{},1000)')
    const result=await launch({electron:process.execPath,root:fixture,profile:path.join(fixture,'profile'),script:'unused',timeoutMs:400,
      request:'',chatId:'x',model:'x',resultFile:path.join(fixture,'result.json'),logFile:path.join(fixture,'requests.log'),dumpDir:path.join(fixture,'dump')})
    assert.equal(result.stopReason,'timeout','close after cancellation must not overwrite timeout as crashed')
    assert.equal(result.cleanupRequestSucceeded,true)
    assert.equal(result.rootExited,true)
    console.log('PASS bench reliability: no false pass, strict arguments, complete accounting, fresh output, minimal profile, bounded verification and timeout cleanup')
  } finally { fs.rmSync(fixture,{recursive:true,force:true}) }
})().catch(error=>{console.error(error);process.exitCode=1})
